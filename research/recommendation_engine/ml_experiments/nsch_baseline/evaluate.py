"""
Evaluate the FROZEN model once on the held-out 2025 records and write the experiment report.

    .venv\\Scripts\\python.exe -m nsch_baseline.evaluate        (run from ml_experiments/)

The model file must match the hash recorded at freezing time; nothing is refitted or re-tuned here.
"""

import json
from datetime import datetime, timezone

import joblib

from . import config, data, metrics


def subgroup(y, p, mask, threshold):
    if mask.sum() == 0 or y[mask].min() == y[mask].max():
        return None
    d = metrics.discrimination(y[mask], p[mask])
    t = metrics.at_threshold(y[mask], p[mask], threshold)
    return {"n": d["n"], "prevalence": d["prevalence"], "roc_auc": d["roc_auc"], "pr_auc": d["pr_auc"],
            "sensitivity": t["sensitivity"], "specificity": t["specificity"]}


def main():
    meta = json.loads((config.ARTIFACT_DIR / "metadata.json").read_text(encoding="utf-8"))
    model_path = config.ARTIFACT_DIR / "model.joblib"
    if data.sha256(model_path) != meta["model_sha256"]:
        raise RuntimeError("Model file differs from the frozen artifact; refusing to evaluate.")
    pipe = joblib.load(model_path)
    threshold = meta["decision_threshold"]["value"]

    X, y, groups = data.load_test()
    p = pipe.predict_proba(X)[:, 1]

    sex = groups["SC_SEX"].to_numpy()
    age = groups["SC_AGE_YEARS"].astype(int).to_numpy()
    results = {
        "evaluated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "model_sha256": meta["model_sha256"],
        "frozen_at_utc": meta["frozen_at_utc"],
        "test_year": config.TEST_YEAR,
        "selected_model": meta["selected_model"],
        "test": metrics.discrimination(y, p),
        "calibration": metrics.calibration(y, p),
        "at_frozen_threshold": metrics.at_threshold(y, p, threshold),
        "prevalence_baseline": metrics.prevalence_baseline(y, meta["train_prevalence"]),
        "provisional_bootstrap_95ci_unweighted_not_design_adjusted": metrics.bootstrap_ci(y, p, seed=config.SEED),
        "subgroups": {
            "sex_male": subgroup(y, p, sex == "1", threshold),
            "sex_female": subgroup(y, p, sex == "2", threshold),
            **{f"age_{a}": subgroup(y, p, age == a, threshold) for a in range(config.AGE_MIN, config.AGE_MAX + 1)},
        },
        "notes": [
            "Unweighted metrics describe the 2025 sample, not the US population.",
            "Confidence intervals are a simple percentile bootstrap and are NOT survey-design adjusted (provisional).",
            "Threshold was fixed on the 2023-2024 validation partition before 2025 was opened.",
        ],
    }
    (config.ARTIFACT_DIR / "test_metrics_2025.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    with open(config.ARTIFACT_DIR / "evaluation_log.jsonl", "a", encoding="utf-8") as log:
        log.write(json.dumps({"evaluated_at_utc": results["evaluated_at_utc"], "model_sha256": meta["model_sha256"],
                              "roc_auc": results["test"]["roc_auc"]}) + "\n")
    write_report(meta, results)

    t, c, a, b = results["test"], results["calibration"], results["at_frozen_threshold"], results["prevalence_baseline"]
    print(f"2025 held-out test: n={t['n']} positives={t['positives']} prevalence={t['prevalence']:.4f}")
    print(f"ROC-AUC {t['roc_auc']:.4f} (baseline 0.5) | PR-AUC {t['pr_auc']:.4f} (no-skill {t['prevalence']:.4f}) | "
          f"Brier {t['brier']:.4f} (prevalence-only {b['brier']:.4f})")
    print(f"Calibration: slope {c['calibration_slope']:.3f}, intercept {c['calibration_intercept']:.3f}, "
          f"mean predicted {c['mean_predicted']:.4f} vs observed {c['observed_rate']:.4f}")
    print(f"At frozen threshold {a['threshold']:.4f}: {a['confusion_matrix']} sensitivity {a['sensitivity']:.3f} "
          f"specificity {a['specificity']:.3f} precision {a['precision']:.3f}")
    print(f"Report written to {config.REPORT_PATH}")


def _pct(x):
    return f"{100 * x:.1f} %"


def write_report(meta, r):
    val = json.loads((config.ARTIFACT_DIR / "validation_metrics.json").read_text(encoding="utf-8"))
    t, c, a, b = r["test"], r["calibration"], r["at_frozen_threshold"], r["prevalence_baseline"]
    ci = r["provisional_bootstrap_95ci_unweighted_not_design_adjusted"]
    cm = a["confusion_matrix"]
    vs = val["selected"]
    lines = [
        "# NSCH K2Q31A Baseline — Experiment Report (`NSCH_EXPERIMENT_REPORT.md`)",
        "",
        f"**Experiment:** {meta['experiment_id']} · **Frozen:** {meta['frozen_at_utc']} · "
        f"**Evaluated on 2025:** {r['evaluated_at_utc']}  ",
        "*Generated by `python -m nsch_baseline.evaluate`; numbers are copied from the saved metric files.*",
        "",
        f"> {config.DISCLAIMER} Not a diagnostic model, not an ADHD presentation classifier, not a longitudinal or "
        "learning-readiness predictor, and not approved for integration into MathQuest.",
        "",
        "## Data and design",
        "",
        "| Partition | Years | n | Positives | Prevalence |",
        "| :--- | :--- | ---: | ---: | ---: |",
        f"| Training | 2023–2024 | {meta['n']['train']:,} | — | {_pct(meta['train_prevalence'])} |",
        f"| Validation | 2023–2024 | {meta['n']['validation']:,} | {vs['positives']:,} | {_pct(vs['prevalence'])} |",
        f"| **Held-out test** | **2025** | {t['n']:,} | {t['positives']:,} | {_pct(t['prevalence'])} |",
        "",
        f"Children aged 6–10 with a valid K2Q31A answer. Split stratified by year × target, seed {meta['seed']}. "
        f"{meta['features']['n_source_features']} conservative Tier A features "
        f"({meta['features']['n_encoded_columns']} encoded columns); no survey weights or year used as predictors. "
        "The 2025 file was not opened during training, model selection or threshold setting.",
        "",
        "## Model selection (validation partition only)",
        "",
        "| Candidate | Params | Val ROC-AUC | Val PR-AUC | Val Brier |",
        "| :--- | :--- | ---: | ---: | ---: |",
    ]
    for cand in val["all_candidates"]:
        lines.append(f"| {cand['family']} | `{json.dumps(cand['params'])}` | {cand['roc_auc']:.4f} | "
                     f"{cand['pr_auc']:.4f} | {cand['brier']:.4f} |")
    lines += [
        "",
        f"**Selected:** {meta['selected_model']['family']} `{json.dumps(meta['selected_model']['params'])}` — "
        f"{meta['selected_model']['selection_rule']}. Decision threshold **{meta['decision_threshold']['value']:.4f}** "
        f"({meta['decision_threshold']['rule']}).",
        "",
        "## Held-out 2025 results (frozen model, evaluated once)",
        "",
        "| Metric | Selected model | Prevalence-only baseline | Provisional 95 % CI* |",
        "| :--- | ---: | ---: | :--- |",
        f"| ROC-AUC | **{t['roc_auc']:.4f}** | 0.5000 | {ci['roc_auc'][0]:.3f}–{ci['roc_auc'][1]:.3f} |",
        f"| PR-AUC | **{t['pr_auc']:.4f}** | {b['pr_auc']:.4f} (= prevalence) | {ci['pr_auc'][0]:.3f}–{ci['pr_auc'][1]:.3f} |",
        f"| Brier score | **{t['brier']:.4f}** | {b['brier']:.4f} (predicts {_pct(b['predicted_probability'])} for all) | "
        f"{ci['brier'][0]:.4f}–{ci['brier'][1]:.4f} |",
        f"| Brier skill vs observed prevalence | {t['brier_skill_vs_observed_prevalence']:.4f} | 0 | — |",
        "",
        "*Simple percentile bootstrap of 2025 records (1,000 resamples), unweighted, **not survey-design adjusted**.",
        "",
        f"**Confusion matrix at the frozen threshold {a['threshold']:.4f}:**",
        "",
        "| | Predicted positive | Predicted negative |",
        "| :--- | ---: | ---: |",
        f"| Reported ADHD history (K2Q31A=1) | TP {cm['tp']:,} | FN {cm['fn']:,} |",
        f"| No reported history (K2Q31A=2) | FP {cm['fp']:,} | TN {cm['tn']:,} |",
        "",
        f"Sensitivity/recall **{a['sensitivity']:.3f}**, specificity **{a['specificity']:.3f}**, precision (PPV) "
        f"**{a['precision']:.3f}**, NPV {a['npv']:.3f}, F1 {a['f1']:.3f}; {_pct(a['predicted_positive_rate'])} of "
        "children flagged.",
        "",
        "**Calibration (2025):** mean predicted "
        f"{_pct(c['mean_predicted'])} vs observed {_pct(c['observed_rate'])} (calibration-in-the-large "
        f"{c['calibration_in_the_large']:+.4f}); logistic calibration slope {c['calibration_slope']:.3f}, "
        f"intercept {c['calibration_intercept']:.3f}.",
        "",
        "| Risk decile | n | Mean predicted | Observed rate |",
        "| ---: | ---: | ---: | ---: |",
    ]
    for i, row in enumerate(c["reliability_deciles"], 1):
        lines.append(f"| {i} | {row['n']} | {row['mean_predicted']:.3f} | {row['observed_rate']:.3f} |")
    lines += ["", "**Subgroups (2025, unweighted):**", "",
              "| Group | n | Prevalence | ROC-AUC | PR-AUC | Sensitivity | Specificity |",
              "| :--- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for name, g in r["subgroups"].items():
        if g:
            lines.append(f"| {name} | {g['n']} | {_pct(g['prevalence'])} | {g['roc_auc']:.3f} | {g['pr_auc']:.3f} | "
                         f"{g['sensitivity']:.3f} | {g['specificity']:.3f} |")
    lines += [
        "",
        "## Interpretation and limitations",
        "",
        f"- 2025 ROC-AUC ({t['roc_auc']:.3f}) is slightly higher than validation ({vs['roc_auc']:.3f}). The pipeline "
        "and features were frozen before 2025 was opened, so this is not tuning to the test year; it reflects sampling "
        "variation and differences in the 2025 sample composition (higher prevalence, different state mix). The "
        "provisional intervals should be read before drawing conclusions from the difference.",
        f"- Discrimination is **modest** (ROC-AUC {t['roc_auc']:.2f}); the model ranks children better than chance but "
        "many children with reported ADHD history receive low scores and most flagged children have no reported "
        "history (see precision). This is expected: only stable/contextual features are used, by design, to avoid "
        "target leakage.",
        "- One threshold for everyone produces very different error profiles by subgroup (see the table: e.g. boys "
        "receive higher scores, giving higher sensitivity but much lower specificity than girls). This mirrors the "
        "higher reported prevalence in boys and must not be read as a property of individual children.",
        "- Missingness is informative: blank answers form their own category, and item non-response is associated with "
        "the outcome. Inputs with many missing values are therefore not representative (the demo warns about this).",
        "- The outcome is parent-reported 'ever told', not a verified diagnosis, and reflects access to care, insurance, "
        "state and reporting practices as well as the child.",
        "- Cross-sectional survey: no feature can be shown to precede the outcome; associations are not causal.",
        "- Official codebook (special missing codes) and survey-design guidance were not available; missing values of "
        "different kinds are pooled, and all uncertainty estimates are provisional and not design-adjusted.",
        "- Metrics are unweighted (sample, not US population). US-only data; no transfer to Sri Lankan children.",
        "- Not for individual use; not integrated into MathQuest.",
        "",
        "## Reproduce",
        "",
        "```",
        "cd research/recommendation_engine/ml_experiments",
        ".venv\\Scripts\\python.exe -m nsch_baseline.train      # 2023-2024 only; freezes the model",
        ".venv\\Scripts\\python.exe -m nsch_baseline.evaluate   # one evaluation on 2025; writes this report",
        ".venv\\Scripts\\python.exe -m nsch_baseline.demo       # prediction + SHAP for one held-out example",
        "```",
        "",
        f"Library versions: `{json.dumps(meta['library_versions'])}`",
        "",
    ]
    config.REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    import sys

    if "--report-only" in sys.argv:
        # Rebuild the report from the saved metric files without re-opening 2025.
        write_report(json.loads((config.ARTIFACT_DIR / "metadata.json").read_text(encoding="utf-8")),
                     json.loads((config.ARTIFACT_DIR / "test_metrics_2025.json").read_text(encoding="utf-8")))
        print(f"Report regenerated from saved metrics: {config.REPORT_PATH}")
    else:
        main()
